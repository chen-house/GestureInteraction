/* 引导视频的时间线：手每一刻在哪（秒）。和演奏版不同，这里要一步步走完 8 步引导，
   所以直接写动作，不走 hands.js 的编排换算。坐标仍然问页面要（yJ / yDeck 由 make_guide.mjs 提供）。
   expect：每次起音应该是什么音高（midi），给检查用。 */
(()=>{
  const R=[
    [1.5,3.5,t=>({x:.85,y:yJ("5"),p:0})],[3.5,4.0,t=>({x:.85,y:yJ("5"),p:1})],[4.0,5.5,t=>({x:.85,y:yJ("5"),p:0})],
    [5.5,6.0,t=>({x:.85,y:yJ("5"),p:1})],[6.0,6.15,t=>({x:.85,y:yJ("3"),p:0})],[6.15,6.6,t=>({x:.85,y:yJ("3"),p:1})],
    [6.6,6.75,t=>({x:.85,y:yJ("1"),p:0})],[6.75,7.3,t=>({x:.85,y:yJ("1"),p:1})],
    [7.3,9.0,t=>({x:lerp(.85,.47,(t-7.3)/1.0),y:yJ("3"),p:0})]];
  /* 边弹边往右挪＝音量变大。捏 0.17 秒、松 0.15 秒，松开那一下就换高度（滤波来得及跟上） */
  const SW=["3","5","6","5","3","5","6","1'"];
  SW.forEach((j,i)=>{ const t0=9+i*0.32, x=lerp(.47,.72,(t0-9)/2.2), nx=SW[i+1];
    R.push([t0,t0+0.17,t=>({x,y:yJ(j),p:1})]); R.push([t0+0.17,t0+0.32,t=>({x,y:yJ(nx||j),p:0})]); });
  R.push([11.6,24.4,t=>({x:.85,y:yJ("5"),p:0})]);
  R.push([24.4,25.0,t=>({x:.85,y:lerp(yJ("5"),yJ("3"),(t-24.4)/.2),p:0})]);     // 先挪到 3 再捏
  const L=[[12.0,13.5,t=>({x:.12,y:yDeck(1),o:1})],[13.5,14.5,t=>({x:.12,y:lerp(yDeck(1),yDeck(3),(t-13.5)/1),o:1})],
    [14.5,16.5,t=>({x:.12,y:yDeck(3),o:1})],[16.5,18.8,t=>({x:.12,y:yDeck(3),o:1,to:lerp(1,.25,(t-16.5)/1.2)})],
    [18.8,20.0,t=>({x:.12,y:yDeck(3),o:1,to:.25})],[20.0,21.2,t=>({x:.12,y:yDeck(3),o:.05,to:.25})],
    [21.2,22.6,t=>({x:lerp(.12,.12+menuDx("柔和"),(t-21.2)/.5),y:yDeck(3),o:.05,to:.25})],[22.6,40,t=>({x:.12+menuDx("柔和"),y:yDeck(3),o:1,to:.25})]];
  const G=[["3",25.0,26.2],["5",26.2,27.0],["6",27.0,28.2],["5",28.2,29.2]];
  const handsAt = t=>{ const h=[]; const l=L.find(s=>t>=s[0]&&t<s[1]); if(l){const q=l[2](t); h.push(at(q.x,q.y,q.o,q.to,0));}
    const gl=G.find(s=>t>=s[1]&&t<s[2]);
    if(gl){ const i=G.indexOf(gl), y0=i?yJ(G[i-1][0]):yJ(gl[0]); h.push(at(.85,lerp(y0,yJ(gl[0]),(t-gl[1])/0.12),1,undefined,1)); }
    else if(t>=29.2&&t<40) h.push(at(.85,yJ("5"),1,undefined,0));
    else { const r=R.find(s=>t>=s[0]&&t<s[1]); if(r){const q=r[2](t); h.push(at(q.x,q.y,1,undefined,q.p));} }
    return h; };
  return { handsAt, duration:31, expect:[67,67,64,60, 64,67,69,67,64,67,69,72, 64] };
})()
